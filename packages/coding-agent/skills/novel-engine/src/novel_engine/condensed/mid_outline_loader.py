"""Load mid_outline chapter-level intents and aggregate them into PLAN context.

The condensed mode previously had no chapter-level plot design data; LLM was
free to invent plans for every 10-chapter batch, which converged on
"observer-record" template structure. This module loads the approved
mid_outline files (generated by generate_mid_outline.py + audited by
audit_mid_outline.py + human-reviewed) and provides a compact digest that the
PLAN prompt can inject as per-chapter core_event constraints.

Design:
- Only entries with status="approved" are included; pending_human and
  needs_regenerate entries are skipped (the LLM plans those chapters freely).
- The digest is a compact JSON list, one entry per chapter, so the PLAN
  prompt can say "chapters with a mid_outline entry must follow the
  core_event; chapters without one follow the type-system constraint".
- No new fields are added to the beat structure; this is pure prompt
  context, not StateDB data.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

_cache: dict[tuple[str, int, int], list[dict]] = {}


def _load_file(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
        return data
    except Exception as exc:
        logger.warning("mid_outline load failed %s: %s", path, exc)
        return {}


def _extract_entries(data: dict, start: int, end: int) -> list[dict]:
    entries = data.get("entries", {})
    result = []
    for ch_num in range(start, end + 1):
        entry = entries.get(str(ch_num))
        if not isinstance(entry, dict):
            continue
        status = entry.get("status", "")
        if status != "approved":
            continue
        core_event = (entry.get("core_event") or "").strip()
        if not core_event:
            continue
        chars = entry.get("characters") or []
        boundary = entry.get("boundary_note")
        result.append({
            "chapter": ch_num,
            "core_event": core_event,
            "characters": chars if isinstance(chars, list) else [],
            "boundary_note": boundary if isinstance(boundary, str) else None,
        })
    return result


def load_mid_outline_batch(planning_dir: str | Path, start: int, end: int) -> list[dict]:
    """Load all approved mid_outline entries for chapters [start, end].

    Scans all mid_outline_*.json files in planning_dir and merges the
    entries that fall within [start, end]. Only entries with
    status="approved" are included. Duplicate chapter numbers are
    deduplicated (first file in sort order wins).
    """
    cache_key = (str(planning_dir), start, end)
    if cache_key in _cache:
        return _cache[cache_key]

    planning_dir = Path(planning_dir)
    files = sorted(planning_dir.glob("mid_outline_*.json"))
    if not files:
        logger.warning("no mid_outline files found in %s", planning_dir)
        _cache[cache_key] = []
        return []

    seen: dict[int, dict] = {}
    for path in files:
        data = _load_file(path)
        for entry in _extract_entries(data, start, end):
            ch = entry["chapter"]
            if ch not in seen:
                seen[ch] = entry

    result = [seen[ch] for ch in sorted(seen)]
    _cache[cache_key] = result
    logger.info(
        "mid_outline: loaded %d approved entries for ch%d-%d from %d files",
        len(result), start, end, len(files),
    )
    return result


def build_plan_digest(entries: list[dict]) -> str:
    """Build a compact JSON string for PLAN prompt injection."""
    if not entries:
        return "[]"
    items = []
    for e in entries:
        item = {
            "chapter": e["chapter"],
            "core_event": e["core_event"],
            "characters": e.get("characters", []),
        }
        if e.get("boundary_note"):
            item["boundary_note"] = e["boundary_note"]
        items.append(item)
    return json.dumps(items, ensure_ascii=False, separators=(",", ":"))


def clear_cache() -> None:
    _cache.clear()
