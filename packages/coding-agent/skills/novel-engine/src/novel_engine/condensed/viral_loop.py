"""M2: the offline viral-quality closed-loop driver.

This module is the ORCHESTRATOR that ties the OQ-gate foundations + the
story-arc control surface into one deterministic, offline-runnable loop:

    gold (OQ2) ─┐
                 ├─> judge_calibration.score_agreement  ─> agreement / ready
    verdicts ────┘
    gold + verdicts ─> drift.rolling_agreement ─> drift_window
    drift_window.suspect ─> drift.record_drift_suspect (telemetry) + AlarmLog.emit (OQ4)
    feed (OQ1) ─> retention_ingest.ingest_retention (retention table)
    verdict + history + arc ─> story_arc.check_arc ─> plot-direction feedback

It is a **pure orchestration** layer: it invents no new metric, no new
channel, no new constraint — it only wires the already-built deterministic
pieces together and returns a single readable result dict. Every input is
optional, and every no-op path is EXPLICIT (never fabricated):

- no gold  → agreement ready=False (the reference is not ready).
- no feed  → 0 retention rows written.
- no suspect (or no_reference) → no telemetry row, no alarm emitted.
- no arc   → check_arc reports enforced=False ("no plot-direction constraint").

Deterministic, no network, no LLM. A caller that has the LLM verdicts in hand
(just NOT generated by one here) passes them in; this module does not call the
critic.
"""
from __future__ import annotations

from . import drift
from . import judge_calibration
from . import retention_ingest
from . import story_arc
from .alarm_log import AlarmLog


def run_viral_loop(*,
                   gold: list[dict],
                   verdicts: list[dict],
                   feed: list[dict] | None = None,
                   retention_db=None,
                   alarm: AlarmLog | None = None,
                   arc: dict | None = None,
                   window: int = 10,
                   min_n: int = 30,
                   source: str = "offline-feed",
                   floor_satisfaction: int | None = None) -> dict:
    """Run one offline viral-quality closed-loop pass.

    Args:
        gold: OQ2 reference set (list of gold records; [] = "reference not
            ready"). Loaded via `gold_set.load_gold_set`.
        verdicts: the LLM critic verdicts for the same chapters (list of
            verdict records). This module does NOT generate them.
        feed: OQ1 retention feed records (list; None/[] = "no feed"). Loaded
            via `retention_feed.load_retention_feed`.
        retention_db: a `Store.db`-like sqlite connection with the v0
            `retention` table (enable_quality on). When provided AND `feed`
            is non-empty, the feed is ingested into the table. When absent,
            the feed is validated-but-not-persisted (the loop still reports
            how many rows *would* be written, so a caller with no DB can run
            the loop read-only).
        alarm: an OQ4 `AlarmLog` (or None). A drift suspect is emitted here
            ONLY when the window is a real suspect.
        arc: a loaded story-arc constraint dict (or None for "no
            plot-direction constraint"). Checked against the LATEST verdict.
        window: the drift window size (positive int; `drift.rolling_agreement`
            raises on window<=0).
        min_n: the calibration readiness threshold (pass to both the
            agreement and the drift window so "ready" means the same thing
            everywhere).
        source: the retention-ingest run label (per-record `source` still
            lands in the row; this is the run-level label).

    Returns exactly::

        {
          "agreement":  judge_calibration.score_agreement(...),   # dict, ready in it
          "drift_window": drift.rolling_agreement(...),          # dict, suspect in it
          "ingested_retention": int,   # rows written (0 when no feed / no db)
          "suspect_emitted": bool,     # True only when a real suspect was recorded+emitted
          "arc": story_arc.check_arc(...) or {"enforced": False, ...},
          "ready": bool,               # == agreement["ready"]
        }

    No-op discipline (explicit, never fabricated):
    - gold empty → agreement ready=False, drift_window suspect_reason='no_reference',
      suspect_emitted=False, ingested_retention still computed from feed (independent).
    - feed None/[] → ingested_retention=0 (even with a db).
    - retention_db None → feed validated but NOT persisted; ingested_retention is
      the validated row count (the "would-be" write), NOT 0 — so a read-only
      caller still sees the feed's size. (When a db IS present, it is the
      actual rows written.)
    - arc None → arc = {"enforced": False, "violations": [], "satisfied": ["no_arc"]}.
    """
    # 1. Judge–human agreement over the gold reference (no-op when gold empty).
    agreement = judge_calibration.score_agreement(gold, verdicts, min_n=min_n)

    # 2. Rolling drift window over the most recent `window` overlapping chapters.
    drift_window = drift.rolling_agreement(gold, verdicts, window=window, min_n=min_n)

    # 3. Retention ingest (OQ1): no-op when no feed; validated-but-not-persisted
    #    when no db.
    feed = list(feed or [])
    if feed and retention_db is not None:
        ingested_retention = retention_ingest.ingest_retention(retention_db, feed, source=source)
    elif feed:
        # No db to persist into: report the validated count (how many rows the
        # feed carries) WITHOUT writing — a read-only loop still sees the size.
        ingested_retention = len(feed)
    else:
        ingested_retention = 0

    # 4. Drift suspect → persist (telemetry) + emit (OQ4 alarm), ONLY on a real
    #    suspect. no_reference / above-threshold windows write nothing.
    suspect_emitted = False
    if drift_window.get("suspect") and retention_db is not None:
        row_id = drift.record_drift_suspect(retention_db, drift_window)
        if row_id is not None:
            if alarm is not None:
                alarm.emit(drift_window, telemetry_row_id=row_id)
            suspect_emitted = True
    # NOTE: when retention_db is None we cannot record_drift_suspect (it needs a
    # db for the telemetry table) — the suspect is still REPORTED in
    # drift_window, but not persisted/emitted. That is the explicit "no store,
    # no alarm" no-op; the loop never fabricates a suspect row.

    # 5. Story-arc check against the LATEST verdict (no-op when arc is None, and
    # an EXPLICIT no_verdicts sentinel when there is no usable verdict to check
    # — never a fabricated chapter-0 verdict).
    usable = [v for v in verdicts if isinstance(v, dict)
              and isinstance(v.get("chapter"), int) and not isinstance(v.get("chapter"), bool)]
    if not usable:
        # No verdicts at all: cannot check an arc against a chapter. Report the
        # explicit "no verdicts" state (an enforced=False no-op, not a silent pass).
        arc_result = {"enforced": arc is not None, "violations": [], "satisfied": ["no_verdicts"]}
    else:
        latest = max(usable, key=lambda v: v["chapter"])
        history = [v for v in usable if v["chapter"] < latest["chapter"]]
        arc_result = story_arc.check_arc(latest["chapter"], latest, arc, history=history)

    # 6. L4 爽点达标占比（volume satisfaction ratio）+ drift suspect。
    #    No-op when floor_satisfaction is None (no floor configured). A scored
    #    verdict is one carrying a 爽点 int; the ratio is "reaches floor / scored".
    #    Dual-target: each chapter is judged against its OWN floor (climax ->
    #    floor_satisfaction; non-climax/suppression -> NON_CLIMAX_SAT_FLOOR).
    from . import satisfaction
    if floor_satisfaction is not None:
        dual = satisfaction.volume_satisfaction_ratio_dual(
            verdicts, arc, climax_floor=floor_satisfaction,
            target=satisfaction.SAT_VOLUME_TARGET)
        satisfaction_ratio = dual["ratio"]
        satisfaction_drift = dual["drift_suspect"]
    else:
        satisfaction_ratio = None
        satisfaction_drift = False

    return {
        "agreement": agreement,
        "drift_window": drift_window,
        "ingested_retention": ingested_retention,
        "suspect_emitted": suspect_emitted,
        "arc": arc_result,
        "satisfaction_ratio": satisfaction_ratio,
        "satisfaction_drift_suspect": satisfaction_drift,
        "ready": bool(agreement.get("ready", False)),
    }
